package bakery.netlify

/**
 * Renders the Netlify platform files (US-7, D11).
 *
 * They are an *output*: the direct API deploy already ships the baked tree, so
 * these files document the site and support the secondary "Netlify builds from
 * a Git repository" mode. Rendering is pure and byte-deterministic.
 */
object NetlifyTomlRenderer {
    fun renderToml(
        options: NetlifyTomlOptions,
        fallbackPublishDir: String,
    ): String {
        val publishDir = options.publishDir.ifBlank { fallbackPublishDir }
        return buildString {
            appendLine("# Generated by bakery (BKY-NETLIFY). Do not edit.")
            appendLine("[build]")
            appendLine("  publish = \"$publishDir\"")
            if (options.redirects) {
                appendLine()
                appendLine("[[redirects]]")
                appendLine("  from = \"/*\"")
                appendLine("  to = \"${options.notFound}\"")
                appendLine("  status = 404")
            }
        }
    }

    fun renderHeaders(): String =
        buildString {
            appendLine("/*")
            appendLine("  X-Content-Type-Options: nosniff")
            appendLine("  X-Frame-Options: DENY")
            appendLine("  Referrer-Policy: strict-origin-when-cross-origin")
        }

    fun renderRedirects(notFound: String): String = "/*  $notFound  404\n"
}
